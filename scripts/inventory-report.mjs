// Writes docs/design/COPY.md (the copy deck) and docs/design/ELEMENTS.md (the
// element inventory) from what scripts/inventory-design.mjs measured.
//
//   node scripts/inventory-report.mjs
//
// Reads docs/design/inventory/before.json (the app before designer run 5),
// after.json when it is there (the app now), copy-changes.json (each string
// that was changed, before and after, as it is in the source) and
// elements-notes.md (the designer's reading of the measured boxes: which
// differences have a reason and which were made one). Everything else in the
// two documents is counted here, not typed.

import fs from 'node:fs'
import { BUDGET, RETIRED, SCREEN_BUDGET, SCREEN_KIND, retiredIn, words } from './copy-standard.mjs'

const DIR = 'docs/design/inventory'
const read = f => (fs.existsSync(`${DIR}/${f}`) ? JSON.parse(fs.readFileSync(`${DIR}/${f}`, 'utf8')) : null)
const before = read('before.json'), after = read('after.json'), changes = read('copy-changes.json') ?? []
const now = after ?? before
const cell = s => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ')
const fmt = n => n.toLocaleString('en-US')
const kindOf = s => {
  if (s.kind === 'text' && /Methods$/.test(s.views[0]) && s.where === 'stage') return 'methods'
  if (/failed to draw/.test(s.views[0]) && /empty state/.test(s.kind)) return 'error'
  if (s.kind === 'note' && /did not open/.test(s.text)) return 'error'
  if (/^Not in this object/.test(s.text)) return 'error'
  return s.kind
}
const app = inv => inv.strings.filter(s => !s.data).map(s => ({ ...s, kind: kindOf(s) }))
const total = inv => {
  const a = app(inv)
  return {
    states: inv.states.length, texts: inv.states.reduce((x, s) => x + s.texts, 0), distinct: inv.strings.length,
    app: a.length, data: inv.strings.length - a.length, words: a.reduce((x, s) => x + s.words, 0),
    own: a.reduce((x, s) => x + s.own, 0), boxes: inv.boxes.reduce((x, b) => x + b.n, 0), saved: inv.saved.length,
  }
}
const over = s => s.own > (BUDGET[s.kind] ?? Infinity)

// ───────────────────────── COPY.md ─────────────────────────
const L = []
const tb = total(before), ta = after ? total(after) : null
L.push('# The copy deck: every word of the studio, counted', '')
L.push('Generated by `node scripts/inventory-report.mjs` from what `scripts/inventory-design.mjs` measured on the',
  'built app in a browser (headless Chromium, light theme, 1,440 by 900). Do not edit: re-measure and re-generate.',
  'The standard these counts are held to is in [DESIGN.md](../DESIGN.md), "Words"; its numbers are',
  '`scripts/copy-standard.mjs`; `scripts/test-copy.mjs` holds them in `npm test`.', '')
L.push('**How a string is counted.** One string is the text of one element as the reader gets it (a sentence with its',
  'inline parts). A word is a run of characters holding a letter or a digit. Numbers and the object\'s own names',
  '(genes, cell types, groups, samples, gene sets) are set aside before strings are compared, so one sentence drawn',
  'for nine cell types is one string, and "the app\'s own words" leaves them out: a budget is for what the app',
  'says, not for what the data is called. Tooltips (`title`), placeholders and accessible names (`aria-label`) are',
  'strings too. A table\'s cells, a key\'s entries, ticks and stat values are data and are counted, not listed.', '')
L.push('**What was walked.** Every tab of the replicated demo; each option of each control in the rail, one at a time;',
  'every menu, picker and popover opened; one key entry isolated; the pointer on a cell; a volcano point under the',
  'pointer and pinned; an enrichment term opened; a gene that is not in the object; a file that is not a bundle; the',
  'error boundary; the running state of each computation (caught 60 ms after its button); every tab of the',
  'wild-type and time-course demos and of the lab bundle (`testdata/lab/family-2x2.zip`); one Save per figure. Not',
  'reached, and so not here: the offline-conversion dialog, messages for a malformed bundle other than "not a zip",',
  'states of a large object (a table cut at N rows), a collection opened from a folder. The source reading in',
  '`scripts/test-copy.mjs` covers those strings.', '')
L.push('## Totals', '', `| | before run 5 | ${ta ? 'now' : ''} |`, '|---|---:|---:|')
for (const [k, label] of [['states', 'states walked'], ['texts', 'text elements met on the walk'], ['distinct', 'distinct strings'],
  ['app', '… the app\'s own'], ['data', '… data (cells, ticks, key entries, values)'], ['words', 'words in the app\'s distinct strings'],
  ['own', '… the app\'s own words in them'], ['boxes', 'controls measured'], ['saved', 'files saved and read']]) {
  L.push(`| ${label} | ${fmt(tb[k])} | ${ta ? fmt(ta[k]) : ''} |`)
}
L.push('')

L.push('## Words on one screen at rest', '', 'The app\'s own words in view in a 1,440 by 900 window, the view as it opens or after its one computation; data beside it.', '',
  '| view | kind | budget | before | now | data words now |', '|---|---|---:|---:|---:|---:|')
for (const [state, kind] of Object.entries(SCREEN_KIND)) {
  const b = before.states.find(s => s.state === state), a = after?.states.find(s => s.state === state)
  L.push(`| ${state} | ${kind} | ${SCREEN_BUDGET[kind]} | ${b?.app ?? ''} | ${a?.app ?? ''} | ${(a ?? b)?.data ?? ''} |`)
}
L.push('')

L.push('## By kind of text', '', 'The app\'s own words per string. "Over" is the number of distinct strings over the budget.', '',
  '| kind | budget | strings before | longest before | over before | strings now | longest now | over now |', '|---|---:|---:|---:|---:|---:|---:|---:|')
const kinds = [...new Set([...app(before), ...(after ? app(after) : [])].map(s => s.kind))].sort()
for (const k of kinds) {
  const b = app(before).filter(s => s.kind === k), a = after ? app(after).filter(s => s.kind === k) : []
  const mx = l => (l.length ? Math.max(...l.map(s => s.own)) : '')
  L.push(`| ${k} | ${BUDGET[k] ?? ''} | ${b.length} | ${mx(b)} | ${b.filter(over).length} | ${after ? a.length : ''} | ${after ? mx(a) : ''} | ${after ? a.filter(over).length : ''} |`)
}
L.push('')

const longest = (inv, n = 10) => app(inv).filter(s => s.kind !== 'methods').sort((x, y) => y.own - x.own).slice(0, n)
L.push('## The longest ten strings outside Methods', '')
for (const [name, inv] of [['Before run 5', before], ...(after ? [['Now', after]] : [])]) {
  L.push(`**${name}**`, '', '| words (own) | kind | where | text |', '|---:|---|---|---|')
  for (const s of longest(inv)) L.push(`| ${s.words} (${s.own}) | ${s.kind} | ${s.state} | ${cell(s.text.length > 420 ? s.text.slice(0, 420) + ' …' : s.text)} |`)
  L.push('')
}

L.push('## Retired terms, as drawn', '', '| retired | use | why | strings before | strings now |', '|---|---|---|---:|---:|')
for (const r of RETIRED) {
  const count = inv => app(inv).filter(s => retiredIn(s.text).includes(r)).length
  L.push(`| \`${r.re.source.replace(/\|/g, '\\|')}\` | ${r.use} | ${r.why} | ${count(before)} | ${after ? count(after) : ''} |`)
}
L.push('')

if (changes.length) {
  const cut = changes.filter(c => !c.after), same = changes.filter(c => c.after)
  const wb = changes.reduce((x, c) => x + words(c.before), 0), wa = changes.reduce((x, c) => x + words(c.after ?? ''), 0)
  L.push('## Every string changed in run 5', '',
    `${changes.length} strings in the source: ${same.length} reworded, ${cut.length} cut whole. Their words: ${fmt(wb)} before, ${fmt(wa)} after.`,
    'As written in the source (a `{…}` is a slot the data fills). Words / characters.', '',
    '| file | before | w / c | after | w / c | why |', '|---|---|---:|---|---:|---|')
  for (const c of changes) {
    L.push(`| ${c.file.replace('src/', '').replace('components/', '')} | ${cell(c.before)} | ${words(c.before)} / ${c.before.length} | ${c.after ? cell(c.after) : '*(cut)*'} | ${c.after ? `${words(c.after)} / ${c.after.length}` : '0 / 0'} | ${c.why ?? ''} |`)
  }
  L.push('')
}

L.push(`## The deck${after ? ', now' : ' (before run 5)'}`, '',
  'Each of the app\'s strings once, under the view where the walk first met it. "own" is the app\'s own words.', '')
const frameWhere = new Set(['bar', 'tabs'])
const groups = new Map()
for (const s of app(now)) {
  const v = frameWhere.has(s.where) && s.views.length > 3 ? 'The frame (bar and tabs)'
    : /^Wild type only/.test(s.views[0]) ? 'The wild-type demo (what the replicated demo did not show)'
      : /^Time course/.test(s.views[0]) ? 'The time-course demo (what the replicated demo did not show)'
        : /^Lab bundle/.test(s.views[0]) ? 'The lab bundle (what the demos did not show)' : s.views[0]
  if (!groups.has(v)) groups.set(v, [])
  groups.get(v).push(s)
}
for (const [v, list] of groups) {
  L.push(`### ${v}`, '', `${list.length} strings, ${fmt(list.reduce((x, s) => x + s.words, 0))} words (${fmt(list.reduce((x, s) => x + s.own, 0))} the app's own).`, '',
    '| where | kind | text | words | own | chars | px |', '|---|---|---|---:|---:|---:|---:|')
  for (const s of list) L.push(`| ${s.where}${s.src !== 'text' ? ` (${s.src})` : ''} | ${s.kind} | ${cell(s.text)} | ${s.words} | ${s.own}${over(s) ? ' **over**' : ''} | ${s.chars} | ${s.px || ''} |`)
  L.push('')
}

L.push('## What a saved figure carries', '', 'One Save per figure on the walk. The legend ("foot") is what Save writes under the drawing; "own" counts its sentences, not its key or its n.', '',
  '| state | file | format | the legend written under the drawing | words (own) |', '|---|---|---|---|---:|')
for (const f of now.saved) {
  const foot = f.format === 'SVG' ? f.foot.map(l => (l.bold ? `**${l.t}**` : l.t)).join(' / ')
    : f.own.filter(t => /[A-Za-z]{3}/.test(t) && / /.test(t)).join(' / ')
  const own = words(foot.replace(/\(n = [\d,]+\)/g, ' ').replace(/[\d,.]+/g, ' '))
  L.push(`| ${f.state} | ${f.file} | ${f.format} | ${cell(foot.length > 600 ? foot.slice(0, 600) + ' …' : foot) || '*(none: the drawing holds its key and n)*'} | ${words(foot)} (${own}) |`)
}
L.push('')
fs.writeFileSync('docs/design/COPY.md', L.join('\n'))

// ───────────────────────── ELEMENTS.md ─────────────────────────
const E = []
E.push('# The element inventory: every control of the studio, measured', '')
E.push('Generated by `node scripts/inventory-report.mjs` from the same walk as [COPY.md](COPY.md). A box is height,',
  'padding (top right bottom left), radius, type size and weight, and edge widths, in CSS px, read from the computed',
  'style of every visible instance in every state walked. The designer\'s reading of these numbers, and what run 5',
  'made one, is the first section; the tables under it are counted.', '')
if (fs.existsSync(`${DIR}/elements-notes.md`)) E.push(fs.readFileSync(`${DIR}/elements-notes.md`, 'utf8').trim(), '')
const boxKey = b => `${b.h} · ${b.pad} · r${b.radius} · ${b.font}/${b.wt} · edge ${b.edge}`
const table = (inv, title) => {
  E.push(`## ${title}`, '', '| kind | boxes | instances | the boxes (height · padding · radius · type · edge), most used first |', '|---|---:|---:|---|')
  const ks = [...new Set(inv.boxes.map(b => b.kind))]
  const rows = []
  for (const k of ks) {
    const m = new Map()
    for (const b of inv.boxes.filter(b => b.kind === k)) {
      const key = boxKey(b)
      if (!m.has(key)) m.set(key, { n: 0, views: new Set(), cls: b.cls, text: b.text })
      const r = m.get(key); r.n += b.n; r.views.add(b.view.replace(/^(Wild type only|Time course|Lab bundle): /, ''))
    }
    const list = [...m].sort((a, b) => b[1].n - a[1].n)
    rows.push([k, list.length, list.reduce((x, [, r]) => x + r.n, 0),
      list.slice(0, 8).map(([key, r]) => `\`${key}\` ×${r.n} (${[...r.views].slice(0, 4).join(', ')}${r.views.size > 4 ? `, +${r.views.size - 4}` : ''}${r.text ? `; e.g. "${cell(r.text.slice(0, 24))}"` : ''})`).join('<br>') + (list.length > 8 ? `<br>… and ${list.length - 8} more` : '')])
  }
  for (const r of rows.sort((a, b) => b[1] - a[1])) E.push(`| ${r[0]} | ${r[1]} | ${fmt(r[2])} | ${r[3]} |`)
  E.push('')
}
if (after) table(after, 'Every kind and its boxes, now')
table(before, 'Every kind and its boxes, before run 5')

E.push('## States', '', 'The first control of each kind the walk could put the pointer and the focus on. A blank means the value did not change from rest.', '',
  '| kind | at rest (ground · ink · edge) | hover | focus (ring) |', '|---|---|---|---|')
for (const [k, s] of Object.entries(now.stateStyles)) {
  const d = (a, b, f) => (a[f] !== b[f] ? `${f} ${b[f]}` : '')
  const hov = ['bg', 'ink', 'edge'].map(f => d(s.rest, s.hover, f)).filter(Boolean).join(' · ')
  const foc = [s.focus.outline !== s.rest.outline ? s.focus.outline : '', s.focus.shadow !== s.rest.shadow ? `shadow ${s.focus.shadow.slice(0, 60)}` : '', d(s.rest, s.focus, 'edge')].filter(Boolean).join(' · ')
  E.push(`| ${k} | ${s.rest.bg} · ${s.rest.ink} · ${s.rest.edge} | ${hov || '*(none)*'} | ${foc || '*(none)*'} |`)
}
E.push('', '## Selected and disabled', '', '| kind | state | ground · ink · edge ink · weight | instances |', '|---|---|---|---:|')
{
  const m = new Map()
  for (const b of now.boxes.filter(b => b.state !== 'default')) {
    const key = `${b.kind}|${b.state}|${b.bg} · ${b.ink} · ${b.edgeInk || 'no edge'} · ${b.wt}`
    m.set(key, (m.get(key) ?? 0) + b.n)
  }
  for (const [k, n] of [...m].sort()) { const [kind, state, sig] = k.split('|'); E.push(`| ${kind} | ${state} | ${sig} | ${n} |`) }
}
E.push('', '## Spacing to the control before it', '', 'The gap from the element before, across (same row) or down, as measured; the three most common per kind.', '',
  '| kind | gaps (px, direction) ×instances |', '|---|---|')
{
  const m = new Map()
  for (const b of now.boxes) for (const [g, n] of Object.entries(b.gaps)) {
    if (!m.has(b.kind)) m.set(b.kind, {})
    m.get(b.kind)[g] = (m.get(b.kind)[g] ?? 0) + n
  }
  for (const [k, g] of m) E.push(`| ${k} | ${Object.entries(g).sort((a, b) => b[1] - a[1]).slice(0, 5).map(([x, n]) => `${x} ×${n}`).join(' · ')} |`)
}
E.push('')
fs.writeFileSync('docs/design/ELEMENTS.md', E.join('\n'))
console.log(`COPY.md: ${L.length} lines; ELEMENTS.md: ${E.length} lines`)
console.log(`before: ${JSON.stringify(tb)}`)
if (ta) console.log(`now:    ${JSON.stringify(ta)}`)
